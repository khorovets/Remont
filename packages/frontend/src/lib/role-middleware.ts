import type { Role } from '@remont/shared'

// =============================================================================
// RoleName — алиас роли пользователя (из @remont/shared)
// =============================================================================

export type RoleName = Role

// =============================================================================
// requireRole — выбрасывает ошибку 403, если роль пользователя не совпадает
// с требуемой
// =============================================================================

export function requireRole(
  user: { userId: number; role: RoleName },
  allowedRole: RoleName,
): void {
  if (user.role !== allowedRole) {
    throw new Error(`Доступ запрещён. Требуется роль: ${allowedRole}`)
  }
}
