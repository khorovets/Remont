// =============================================================================
// API Types — Remont.by
// =============================================================================

// -----------------------------------------------------------------------------
// ErrorCode — возможные коды ошибок API
// -----------------------------------------------------------------------------

export type ErrorCode =
  | 'VALIDATION_ERROR'
  | 'UNAUTHORIZED'
  | 'FORBIDDEN'
  | 'NOT_FOUND'
  | 'CONFLICT'
  | 'INTERNAL_ERROR'

// -----------------------------------------------------------------------------
// ApiError — стандартная структура ошибки API
// -----------------------------------------------------------------------------

export interface ApiError {
  code: ErrorCode
  message: string
}

// -----------------------------------------------------------------------------
// ApiResponse<T> — результат API-запроса (успех или ошибка)
// -----------------------------------------------------------------------------

export type ApiResponse<T> =
  | { data: T; error: null }
  | { data: null; error: ApiError }

// -----------------------------------------------------------------------------
// Pagination — метаинформация о пагинации
// -----------------------------------------------------------------------------

export interface Pagination {
  page: number
  limit: number
  total: number
  total_pages: number
}

// -----------------------------------------------------------------------------
// PaginatedResponse<T> — ответ с пагинированным списком
// -----------------------------------------------------------------------------

export interface PaginatedResponse<T> {
  items: T[]
  pagination: Pagination
}
