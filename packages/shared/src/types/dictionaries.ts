// =============================================================================
// Dictionary Types — Remont.by
// =============================================================================

// -----------------------------------------------------------------------------
// Region — область
// -----------------------------------------------------------------------------

export interface Region {
  id: number
  name: string
  slug: string
  sort_order: number
}

// -----------------------------------------------------------------------------
// City — город / населённый пункт
// -----------------------------------------------------------------------------

export interface City {
  id: number
  name: string
  slug: string
  region_id: number
  /** Денормализованное имя региона (заполняется на уровне API/запроса) */
  region_name?: string
}

// -----------------------------------------------------------------------------
// CategoryGroup — родительская группа категорий (parent_id = null)
// -----------------------------------------------------------------------------

export interface CategoryGroup {
  id: number
  name: string
  slug: string
}

// -----------------------------------------------------------------------------
// Category — категория работ / услуги
// -----------------------------------------------------------------------------

export interface Category {
  id: number
  name: string
  slug: string
  /** ID родительской группы; null — если это сама группа */
  parent_id?: number | null
  /** Произвольные метаданные: { unit, material, surface, … } */
  metadata: Record<string, string>
  /** Денормализованное имя родительской группы (заполняется на уровне API/запроса) */
  group_name?: string
}
