import { z } from 'zod';

// -----------------------------------------------------------------------------
// createReviewSchema — создание отзыва
// -----------------------------------------------------------------------------

export const createReviewSchema = z.object({
  order_id: z
    .number({ required_error: 'ID заказа обязателен' })
    .int('ID заказа должен быть целым числом')
    .positive('ID заказа должен быть положительным числом'),
  contractor_id: z
    .number({ required_error: 'ID исполнителя обязателен' })
    .int('ID исполнителя должен быть целым числом')
    .positive('ID исполнителя должен быть положительным числом'),
  category_id: z
    .number({ required_error: 'ID категории обязателен' })
    .int('ID категории должен быть целым числом')
    .positive('ID категории должен быть положительным числом'),
  rating: z
    .number({ required_error: 'Оценка обязательна' })
    .int('Оценка должна быть целым числом')
    .min(1, 'Оценка должна быть от 1 до 5')
    .max(5, 'Оценка должна быть от 1 до 5'),
  text: z
    .string()
    .max(2000, 'Текст отзыва не должен превышать 2000 символов')
    .optional(),
});

// -----------------------------------------------------------------------------
// Inferred types
// -----------------------------------------------------------------------------

export type CreateReviewInput = z.infer<typeof createReviewSchema>;
